-- =====================================================================
-- 凌霄 · 修复参数名乱码（V17）
-- =====================================================================
-- 现象：参数设置页 sys.account.maxRetryCount 的中文名显示成 ????????。
--
-- 根因：V14 的种子数据本身是 UTF-8 中文，但迁移应用后不久，一个验证脚本
-- 通过 PUT /api/admin/system/config/{id} 改值，请求体不是 UTF-8，
-- 把 config_name / remark 覆盖成了问号（行内 update_time 与 V14 应用时间只差 28 秒）。
-- 同一个 INSERT 里的另外两行正常，所以不是迁移文件编码问题。
--
-- 这次修复做两件事：
--   1) 把内置参数名 / 说明恢复成中文；
--   2) 前端参数名改为走 i18n（config.sys.account.maxRetryCount），
--      以后即使库里再被写脏，页面也不会显示乱码。
--
-- 只按 config_key 更新，可重复执行；新装环境 V14 已是正确中文，等价于空操作。
-- =====================================================================

UPDATE sys_config
SET config_name = '登录失败锁定阈值',
    remark      = '连续登录失败达到该次数后锁定账号（3~10 次）',
    update_time = NOW(3)
WHERE config_key = 'sys.account.maxRetryCount';
